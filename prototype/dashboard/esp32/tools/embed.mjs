/**
 * PROTOTYPE — throwaway (issue #7).
 *
 * Turns the dashboard page into C string literals so the ESP32 can serve the
 * very same index.html / style.css / app.js the laptop prototype serves, with
 * no filesystem and no build step on the device. Also stamps the build time:
 * a board with no RTC and no NTP only ever knows when it was flashed, so that
 * is what it tells the page.
 *
 *   node tools/embed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pub = path.join(here, '..', '..', 'public');
const out = path.join(here, '..', 'src', 'web_assets.h');

const ASSETS = [
  ['INDEX_HTML', 'index.html', 'text/html; charset=utf-8'],
  ['STYLE_CSS', 'style.css', 'text/css'],
  ['APP_JS', 'app.js', 'text/javascript'],
];

// A C string literal can carry any byte except NUL; these three are all it takes.
const escape = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');

const parts = [
  '/* generated by tools/embed.mjs — do not edit, do not commit by hand */',
  '#pragma once',
  '',
  '#define BUILD_EPOCH_MS ' + Date.now() + 'LL   /* the only clock this board has */',
  '',
];

for (const [name, file, mime] of ASSETS) {
  const src = fs.readFileSync(path.join(pub, file), 'utf8');
  parts.push(`/* ${file} — ${src.length} bytes, served as ${mime} */`);
  parts.push(`#define ${name}_MIME "${mime}"`);
  parts.push(`static const char ${name}[] = "${escape(src)}";`);
  parts.push('');
}

fs.writeFileSync(out, parts.join('\n'));
const total = ASSETS.reduce((n, [, f]) => n + fs.statSync(path.join(pub, f)).size, 0);
console.log(`${path.relative(process.cwd(), out)}: ${ASSETS.length} assets, ${(total / 1024).toFixed(1)} kB, build stamp ${new Date().toISOString()}`);
